class Platform(Enum):
    """Target platforms for builds."""
    WIN64 = "Win64"
    LINUX = "Linux"
    MAC = "Mac"
    ANDROID = "Android"
    IOS = "iOS"
    PS5 = "PS5"
    XBOX_SERIES = "XboxSeriesX"


class BuildConfiguration(Enum):
    """Build configurations."""
    DEVELOPMENT = "Development"
    SHIPPING = "Shipping"
    DEBUG = "Debug"
    TEST = "Test"


class CIPlatform(Enum):
    """CI/CD platforms."""
    JENKINS = auto()
    GITLAB = auto()
    GITHUB_ACTIONS = auto()
    AZURE_DEVOPS = auto()
    TEAMCITY = auto()


@dataclass
class BuildStep:
    """A single build step."""
    name: str
    command: str
    timeout_minutes: int = 60
    continue_on_error: bool = False
    condition: str = ""
    environment: dict[str, str] = field(default_factory=dict)


@dataclass
class PipelineConfig:
    """Configuration for a CI/CD pipeline."""
    project_name: str
    engine_version: str
    target_platforms: list[Platform]
    configurations: list[BuildConfiguration]
    
    # Build options
    cook_content: bool = True
    package_build: bool = True
    archive_build: bool = True
    run_tests: bool = True
    
    # Environment
    ue_root: str = "C:/Program Files/Epic Games/UE_5.4"
    build_output: str = "./Build"
    
    # Notifications
    notify_slack: bool = False
    slack_webhook: str = ""
    notify_email: bool = False
    email_recipients: list[str] = field(default_factory=list)
    
    # Advanced
    custom_build_args: str = ""
    pre_build_steps: list[BuildStep] = field(default_factory=list)
    post_build_steps: list[BuildStep] = field(default_factory=list)


