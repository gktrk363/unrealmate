class GitLabCIGenerator:
    """Generate GitLab CI/CD configuration."""
    
    def generate(self, config: PipelineConfig) -> str:
        """Generate .gitlab-ci.yml content."""
        lines = [
            "# Generated by UnrealMate",
            f"# Project: {config.project_name}",
            "",
            "variables:",
            f"  UE_ROOT: '{config.ue_root}'",
            f"  PROJECT_NAME: '{config.project_name}'",
            "  BUILD_OUTPUT: './Build'",
            "",
            "stages:",
            "  - prepare",
            "  - build",
            "  - test",
            "  - deploy",
            "",
            "default:",
            "  tags:",
            "    - unreal",
            "    - windows",
            "",
            "# Prepare stage",
            "prepare:",
            "  stage: prepare",
            "  script:",
            "    - echo 'Preparing build environment...'",
            "  artifacts:",
            "    paths:",
            "      - Intermediate/",
            "    expire_in: 1 day",
            "",
        ]
        
        # Build jobs for each platform
        for platform in config.target_platforms:
            for build_config in config.configurations:
                job_name = f"build_{platform.value.lower()}_{build_config.value.lower()}"
                lines.extend([
                    f"# Build {platform.value} {build_config.value}",
                    f"{job_name}:",
                    "  stage: build",
                    "  script:",
                    "    - $UE_ROOT/Engine/Build/BatchFiles/RunUAT.bat BuildCookRun",
                    "      -project=\"$CI_PROJECT_DIR/$PROJECT_NAME.uproject\"",
                    f"      -targetplatform={platform.value}",
                    f"      -clientconfig={build_config.value}",
                ])
                
                if config.cook_content:
                    lines.append("      -cook")
                
                if config.package_build:
                    lines.append("      -stage -pak -package")
                
                if config.archive_build:
                    lines.append("      -archive -archivedirectory=\"$BUILD_OUTPUT\"")
                
                lines.extend([
                    "      -build -compile -unattended -utf8output",
                    "  artifacts:",
                    "    paths:",
                    "      - Build/",
                    "    expire_in: 1 week",
                    "  timeout: 4 hours",
                    "",
                ])
        
        # Test job
        if config.run_tests:
            lines.extend([
                "# Run automated tests",
                "test:",
                "  stage: test",
                "  script:",
                "    - $UE_ROOT/Engine/Binaries/Win64/UnrealEditor-Cmd.exe",
                "      \"$CI_PROJECT_DIR/$PROJECT_NAME.uproject\"",
                "      -ExecCmds=\"Automation RunTests Now\"",
                "      -Unattended -NoPause -Log",
                "  artifacts:",
                "    reports:",
                "      junit: TestResults/*.xml",
                "  allow_failure: true",
                "",
            ])
        
        # Deploy job
        lines.extend([
            "# Deploy (manual trigger)",
            "deploy:",
            "  stage: deploy",
            "  script:",
            "    - echo 'Deploying build...'",
            "  when: manual",
            "  only:",
            "    - main",
            "    - tags",
            "",
        ])
        
        return "\n".join(lines)
    
    def save(self, config: PipelineConfig, output_path: Path) -> None:
        """Save pipeline to file."""
        content = self.generate(config)
        output_path.write_text(content, encoding="utf-8")
        console.print(f"[green]✓ GitLab CI saved to {output_path}[/green]")


