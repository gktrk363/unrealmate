class CICDGenerator:
    """Main class for generating CI/CD pipelines."""
    
    def __init__(self, project_path: Path):
        self.project_path = project_path
        self.jenkins = JenkinsPipelineGenerator()
        self.gitlab = GitLabCIGenerator()
        self.azure = AzureDevOpsPipelineGenerator()
        self.docker = DockerfileGenerator()
        self.versioning = BuildVersioning(project_path)
    
    def generate_all(
        self,
        config: PipelineConfig,
        output_dir: Optional[Path] = None,
    ) -> dict[str, Path]:
        """Generate all CI/CD configurations."""
        output = output_dir or self.project_path
        output.mkdir(parents=True, exist_ok=True)
        
        generated = {}
        
        # Jenkins
        jenkins_path = output / "Jenkinsfile"
        self.jenkins.save(config, jenkins_path)
        generated["jenkins"] = jenkins_path
        
        # GitLab
        gitlab_path = output / ".gitlab-ci.yml"
        self.gitlab.save(config, gitlab_path)
        generated["gitlab"] = gitlab_path
        
        # Azure DevOps
        azure_path = output / "azure-pipelines.yml"
        self.azure.save(config, azure_path)
        generated["azure"] = azure_path
        
        # Docker
        self.docker.save(config, output)
        generated["docker"] = output / "Dockerfile"
        
        return generated
    
    def generate_for_platform(
        self,
        platform: CIPlatform,
        config: PipelineConfig,
        output_path: Optional[Path] = None,
    ) -> Path:
        """Generate pipeline for a specific CI platform."""
        if platform == CIPlatform.JENKINS:
            path = output_path or self.project_path / "Jenkinsfile"
            self.jenkins.save(config, path)
            return path
        
        elif platform == CIPlatform.GITLAB:
            path = output_path or self.project_path / ".gitlab-ci.yml"
            self.gitlab.save(config, path)
            return path
        
        elif platform == CIPlatform.AZURE_DEVOPS:
            path = output_path or self.project_path / "azure-pipelines.yml"
            self.azure.save(config, path)
            return path
        
        else:
            raise ValueError(f"Unsupported CI platform: {platform}")
    
    def list_supported_platforms(self) -> Table:
        """List supported CI/CD platforms."""
        table = Table(title="Supported CI/CD Platforms")
        table.add_column("Platform", style="cyan")
        table.add_column("Output File")
        table.add_column("Status")
        
        platforms = [
            ("Jenkins", "Jenkinsfile", "✓ Supported"),
            ("GitLab CI/CD", ".gitlab-ci.yml", "✓ Supported"),
            ("Azure DevOps", "azure-pipelines.yml", "✓ Supported"),
            ("GitHub Actions", ".github/workflows/*.yml", "✓ Supported"),
            ("TeamCity", ".teamcity/settings.kts", "Coming Soon"),
            ("CircleCI", ".circleci/config.yml", "Coming Soon"),
        ]
        
        for name, output, status in platforms:
            style = "green" if "Supported" in status else "dim"
            table.add_row(name, output, f"[{style}]{status}[/{style}]")
        
        return table

