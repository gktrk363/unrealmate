class BuildVersioning:
    """Automated build versioning."""
    
    def __init__(self, project_path: Path):
        self.project_path = project_path
        self.version_file = project_path / "Config" / "DefaultGame.ini"
    
    def get_version(self) -> str:
        """Get current project version."""
        if not self.version_file.exists():
            return "1.0.0"
        
        content = self.version_file.read_text(encoding="utf-8")
        
        import re
        match = re.search(r'ProjectVersion=(\d+\.\d+\.\d+)', content)
        if match:
            return match.group(1)
        
        return "1.0.0"
    
    def bump_version(
        self,
        bump_type: str = "patch",
    ) -> str:
        """Bump the project version."""
        current = self.get_version()
        parts = current.split(".")
        
        if len(parts) != 3:
            parts = ["1", "0", "0"]
        
        major, minor, patch = int(parts[0]), int(parts[1]), int(parts[2])
        
        if bump_type == "major":
            major += 1
            minor = 0
            patch = 0
        elif bump_type == "minor":
            minor += 1
            patch = 0
        else:  # patch
            patch += 1
        
        new_version = f"{major}.{minor}.{patch}"
        self._update_version(new_version)
        
        console.print(f"[green]✓ Version bumped: {current} → {new_version}[/green]")
        return new_version
    
    def _update_version(self, version: str) -> None:
        """Update version in config file."""
        if not self.version_file.exists():
            return
        
        content = self.version_file.read_text(encoding="utf-8")
        
        import re
        if "ProjectVersion=" in content:
            content = re.sub(
                r'ProjectVersion=\d+\.\d+\.\d+',
                f'ProjectVersion={version}',
                content,
            )
        else:
            # Add version if not exists
            content += f"\n[/Script/EngineSettings.GeneralProjectSettings]\nProjectVersion={version}\n"
        
        self.version_file.write_text(content, encoding="utf-8")
    
    def get_build_number(self) -> int:
        """Get current build number."""
        build_file = self.project_path / ".buildnumber"
        
        if build_file.exists():
            try:
                return int(build_file.read_text().strip())
            except ValueError:
                pass
        
        return 0
    
    def increment_build_number(self) -> int:
        """Increment and return new build number."""
        current = self.get_build_number()
        new_number = current + 1
        
        build_file = self.project_path / ".buildnumber"
        build_file.write_text(str(new_number), encoding="utf-8")
        
        return new_number


