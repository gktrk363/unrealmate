class DockerfileGenerator:
    """Generate Dockerfile for UE builds."""
    
    def generate(self, config: PipelineConfig) -> str:
        """Generate Dockerfile content."""
        lines = [
            "# Generated by UnrealMate",
            f"# Project: {config.project_name}",
            "",
            "# Base image with Unreal Engine",
            "FROM ghcr.io/epicgames/unreal-engine:dev-5.4 AS builder",
            "",
            "# Set working directory",
            "WORKDIR /project",
            "",
            "# Copy project files",
            "COPY . .",
            "",
            "# Build the project",
            "RUN /UnrealEngine/Engine/Build/BatchFiles/RunUAT.sh BuildCookRun \\",
            f"    -project=/project/{config.project_name}.uproject \\",
            "    -targetplatform=Linux \\",
            "    -clientconfig=Shipping \\",
        ]
        
        if config.cook_content:
            lines.append("    -cook \\")
        
        if config.package_build:
            lines.append("    -stage -pak -package \\")
        
        lines.extend([
            "    -build -compile \\",
            "    -archive -archivedirectory=/project/Build \\",
            "    -unattended -utf8output",
            "",
            "# Runtime image",
            "FROM ubuntu:22.04 AS runtime",
            "",
            "# Install runtime dependencies",
            "RUN apt-get update && apt-get install -y \\",
            "    libgl1 libx11-6 libxcursor1 \\",
            "    && rm -rf /var/lib/apt/lists/*",
            "",
            "# Copy built game",
            f"COPY --from=builder /project/Build/Linux/{config.project_name} /game",
            "",
            "WORKDIR /game",
            "",
            "# Entry point",
            f'ENTRYPOINT ["./{config.project_name}"]',
            "",
        ])
        
        return "\n".join(lines)
    
    def generate_compose(self, config: PipelineConfig) -> str:
        """Generate docker-compose.yml content."""
        return f"""# Generated by UnrealMate
# Project: {config.project_name}

version: '3.8'

services:
  build:
    build:
      context: .
      dockerfile: Dockerfile
      target: builder
    volumes:
      - ./Build:/project/Build
    environment:
      - UE_ROOT=/UnrealEngine

  game-server:
    build:
      context: .
      dockerfile: Dockerfile
      target: runtime
    ports:
      - "7777:7777/udp"
    restart: unless-stopped
"""
    
    def save(self, config: PipelineConfig, output_dir: Path) -> None:
        """Save Docker files."""
        dockerfile = self.generate(config)
        compose = self.generate_compose(config)
        
        (output_dir / "Dockerfile").write_text(dockerfile, encoding="utf-8")
        (output_dir / "docker-compose.yml").write_text(compose, encoding="utf-8")
        
        console.print(f"[green]✓ Docker files saved to {output_dir}[/green]")


