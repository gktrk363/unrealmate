class JenkinsPipelineGenerator:
    """Generate Jenkins pipeline files."""
    
    def generate(self, config: PipelineConfig) -> str:
        """Generate a Jenkinsfile."""
        lines = [
            "// Generated by UnrealMate",
            f"// Project: {config.project_name}",
            "",
            "pipeline {",
            "    agent any",
            "",
            "    environment {",
            f"        UE_ROOT = '{config.ue_root}'",
            f"        PROJECT_NAME = '{config.project_name}'",
            "        BUILD_OUTPUT = '${WORKSPACE}/Build'",
            "    }",
            "",
            "    options {",
            "        timeout(time: 4, unit: 'HOURS')",
            "        buildDiscarder(logRotator(numToKeepStr: '10'))",
            "        timestamps()",
            "    }",
            "",
            "    stages {",
        ]
        
        # Checkout stage
        lines.extend([
            "        stage('Checkout') {",
            "            steps {",
            "                checkout scm",
            "            }",
            "        }",
            "",
        ])
        
        # Pre-build steps
        if config.pre_build_steps:
            lines.extend([
                "        stage('Pre-Build') {",
                "            steps {",
            ])
            for step in config.pre_build_steps:
                lines.append(f"                sh '{step.command}'")
            lines.extend([
                "            }",
                "        }",
                "",
            ])
        
        # Build stage for each platform
        for platform in config.target_platforms:
            for build_config in config.configurations:
                stage_name = f"Build {platform.value} {build_config.value}"
                lines.extend([
                    f"        stage('{stage_name}') {{",
                    "            steps {",
                    "                script {",
                    self._get_build_command(config, platform, build_config),
                    "                }",
                    "            }",
                    "        }",
                    "",
                ])
        
        # Test stage
        if config.run_tests:
            lines.extend([
                "        stage('Run Tests') {",
                "            steps {",
                "                script {",
                "                    def testCmd = \"${UE_ROOT}/Engine/Binaries/Win64/UnrealEditor-Cmd.exe\"",
                f"                    testCmd += \" ${{WORKSPACE}}/{config.project_name}.uproject\"",
                "                    testCmd += \" -ExecCmds=\\\"Automation RunTests Now\\\"\"",
                "                    testCmd += \" -Unattended -NoPause -Log\"",
                "                    bat testCmd",
                "                }",
                "            }",
                "        }",
                "",
            ])
        
        # Archive stage
        if config.archive_build:
            lines.extend([
                "        stage('Archive') {",
                "            steps {",
                "                archiveArtifacts artifacts: 'Build/**/*', fingerprint: true",
                "            }",
                "        }",
                "",
            ])
        
        # Post-build steps
        if config.post_build_steps:
            lines.extend([
                "        stage('Post-Build') {",
                "            steps {",
            ])
            for step in config.post_build_steps:
                lines.append(f"                sh '{step.command}'")
            lines.extend([
                "            }",
                "        }",
                "",
            ])
        
        lines.append("    }")  # End stages
        
        # Post section
        lines.extend([
            "",
            "    post {",
            "        always {",
            "            cleanWs()",
            "        }",
            "        success {",
        ])
        
        if config.notify_slack:
            lines.append("            slackSend(color: 'good', message: 'Build succeeded: ${env.JOB_NAME} #${env.BUILD_NUMBER}')")
        
        lines.extend([
            "            echo 'Build succeeded!'",
            "        }",
            "        failure {",
        ])
        
        if config.notify_slack:
            lines.append("            slackSend(color: 'danger', message: 'Build failed: ${env.JOB_NAME} #${env.BUILD_NUMBER}')")
        
        lines.extend([
            "            echo 'Build failed!'",
            "        }",
            "    }",
            "}",
        ])
        
        return "\n".join(lines)
    
    def _get_build_command(
        self,
        config: PipelineConfig,
        platform: Platform,
        build_config: BuildConfiguration,
    ) -> str:
        """Generate build command for a platform."""
        cmd_parts = [
            "                    def buildCmd = \"${UE_ROOT}/Engine/Build/BatchFiles/RunUAT.bat\"",
            "                    buildCmd += \" BuildCookRun\"",
            f"                    buildCmd += \" -project=${{WORKSPACE}}/{config.project_name}.uproject\"",
            f"                    buildCmd += \" -targetplatform={platform.value}\"",
            f"                    buildCmd += \" -clientconfig={build_config.value}\"",
        ]
        
        if config.cook_content:
            cmd_parts.append("                    buildCmd += \" -cook\"")
        
        if config.package_build:
            cmd_parts.append("                    buildCmd += \" -stage -pak -package\"")
        
        if config.archive_build:
            cmd_parts.append("                    buildCmd += \" -archive -archivedirectory=${BUILD_OUTPUT}\"")
        
        cmd_parts.extend([
            "                    buildCmd += \" -build -compile\"",
            "                    buildCmd += \" -unattended -utf8output\"",
            "                    bat buildCmd",
        ])
        
        return "\n".join(cmd_parts)
    
    def save(self, config: PipelineConfig, output_path: Path) -> None:
        """Save pipeline to file."""
        content = self.generate(config)
        output_path.write_text(content, encoding="utf-8")
        console.print(f"[green]✓ Jenkins pipeline saved to {output_path}[/green]")


